//
// Jusqu'ici, une ambiance était une simple recherche de playlists sur Deezer :
// on prenait les trois playlists les plus suivies dont le titre ressemblait au
// thème, et on mélangeait leurs morceaux. Ces playlists sont faites par des
// inconnus, et la recherche de Deezer répond aussi sur la description et le
// contenu. Résultat constaté chez Chachou le 23/08 :
//
//   « Chanson française (Brel, Piaf…) » → Sam Smith, Lewis Capaldi,
//     OneRepublic, Bruno Mars EN BONNES RÉPONSES (une playlist de ballades
//     tristes avait été aspirée) ;
//   « Variété française » → Spice Girls, Britney Spears, Harry Styles,
//     Whitney Houston ;
//   « Années 2010 » → Billie Jean, Africa, Wake Me Up Before You Go-Go,
//     Sexual Healing… c'est-à-dire les années 80.
//
// La correction ne consiste pas à mieux filtrer une source non fiable, mais à
// changer de source : ici, chaque ambiance nomme ses artistes. Deezer ne sert
// plus qu'à retrouver les enregistrements et leurs extraits.
//
// FORMAT : 'Artiste' ou 'Artiste|Titre|Titre'.
//   - sans titre : on prend les morceaux les plus écoutés de l'artiste ;
//   - avec titres : on ne garde que ceux-là. C'est indispensable pour les
//     décennies — sans cela, « Années 90 » ramènerait le dernier album de
//     Mylène Farmer.

