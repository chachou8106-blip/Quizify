// Ambiances sans base d'artistes : on retombe sur les playlists Deezer, mais
// filtrées beaucoup plus sévèrement (voir index.js).
export const SANS_BASE = new Set(['hits du moment']);

// Mots dont la présence dans le titre d'une playlist prouve qu'elle parle bien
// du thème demandé. Sert au chemin de secours.
export const SYNONYMES = {
  disney: ['disney', 'pixar'],
  'generiques de series': ['serie', 'series', 'generique', 'generiques', 'tv'],
};

export function cleAmbiance(nom) {
  return String(nom)
    .normalize('NFD').replace(/\p{Diacritic}/gu, '')
    .toLowerCase()
    .replace(/[()…]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// Retrouve l'ambiance correspondant au libellé affiché dans l'application.
// « Chanson française (Brel, Piaf…) » → 'chanson francaise brel piaf'.
export function trouverAmbiance(libelle) {
  const c = cleAmbiance(libelle).replace(/,/g, '');
  if (AMBIANCES[c]) return AMBIANCES[c];
  for (const [cle, liste] of Object.entries(AMBIANCES)) {
    if (c.startsWith(cle) || cle.startsWith(c)) return liste;
  }
  return null;
}

export function estSansBase(libelle) {
  const c = cleAmbiance(libelle).replace(/,/g, '');
  for (const cle of SANS_BASE) if (c.startsWith(cle) || cle.startsWith(c)) return true;
  return false;
}
